// Reproducible, offline derivation from the already pinned Natural Earth inputs.
import {createHash} from 'node:crypto';
import {readFile,writeFile} from 'node:fs/promises';
import path from 'node:path';
const root=path.resolve(import.meta.dirname,'..');
const digest=bytes=>createHash('sha256').update(bytes).digest('hex');
const provenance=JSON.parse(await readFile(path.join(root,'docs/provenance/map-data.json'),'utf8'));
const name='ne_10m_admin_0_countries';
const input=provenance.sources.find(row=>row.name===name);
const bytes=await readFile(path.join(root,'.build/map-source',name+'.geojson'));
if(bytes.length!==input.bytes||digest(bytes)!==input.sha256)throw Error('Natural Earth input integrity failed');
const countries=JSON.parse(bytes),locations={},populations=new Map();
for(const feature of countries.features){
  const p=feature.properties,code=p.ISO_A2_EH;
  if(!/^[A-Z]{2}$/.test(code)||!Number.isFinite(p.LABEL_X)||!Number.isFinite(p.LABEL_Y))continue;
  const polygons=feature.geometry.type==='Polygon'?[feature.geometry.coordinates]:feature.geometry.coordinates;
  const boxes=polygons.map(polygon=>{
    const points=polygon[0];
    return [Math.min(...points.map(x=>x[0])),Math.min(...points.map(x=>x[1])),Math.max(...points.map(x=>x[0])),Math.max(...points.map(x=>x[1]))].map(x=>Math.round(x*10000));
  });
  const point=[Math.round(p.LABEL_Y*10000),Math.round(p.LABEL_X*10000)],population=Number(p.POP_EST)||0;
  if(locations[code]){
    locations[code].boxes.push(...boxes);
    if(population>(populations.get(code)||0))locations[code].point=point;
  }else locations[code]={point,boxes};
  populations.set(code,Math.max(populations.get(code)||0,population));
}
const worldPath=provenance.outputs.find(row=>/\/map-world(?:-[a-f0-9]{8})?\.js$/.test(row.path)).path,worldBytes=await readFile(path.join(root,worldPath));
const worldSource=provenance.outputs.find(row=>row.path===worldPath);
if(digest(worldBytes)!==worldSource.sha256)throw Error('Curated map integrity failed');
const world=JSON.parse(worldBytes.toString().match(/export const MAP_WORLD = ([\s\S]+);\s*$/)[1]);
const fold=value=>value.normalize('NFKD').replace(/\p{M}/gu,'').toLowerCase().replace(/[^\p{L}\p{N}]+/gu,' ').trim();
const places=[...new Set(world.labels.filter(row=>row.kind==='city').map(row=>fold(row.name)))].sort();
const outputs=[];
for(const [relative,exportName,value]of [['site/assets/country-locations.js','COUNTRY_LOCATIONS',Object.fromEntries(Object.entries(locations).sort())],['site/assets/place-vocabulary.js','PLACE_TERMS',places]]){
  const text=`// Natural Earth v5.1.2, public domain. Generated by scripts/build-discovery-geography.mjs. Coordinates use integer 1/10000 degrees.\nexport const ${exportName} = ${JSON.stringify(value)};\n`;
  await writeFile(path.join(root,relative),text);outputs.push({path:relative,bytes:Buffer.byteLength(text),sha256:digest(text)});
}
const result={source:{path:input.name,sha256:input.sha256},curatedSource:{path:worldPath,sha256:worldSource.sha256},countries:Object.keys(locations).length,places:places.length,outputs};
await writeFile(path.join(root,'docs/provenance/discovery-geography.json'),JSON.stringify(result,null,2)+'\n');
console.log(JSON.stringify(result));
