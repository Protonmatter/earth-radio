// Explicit offline curation. Only --download retrieves the fixed, hash-pinned
// public inputs; no application build or imported function starts network work.
import {createHash} from 'node:crypto';
import {readFile,writeFile,lstat,mkdir,realpath} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const root=path.resolve(import.meta.dirname,'..');
const digest=bytes=>createHash('sha256').update(bytes).digest('hex');
const compare=(a,b)=>a<b?-1:a>b?1:0;
export const PLACE_INPUTS=Object.freeze([
 {name:'ne_10m_populated_places_simple.geojson',revision:'Natural Earth v5.1.2',url:'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/v5.1.2/geojson/ne_10m_populated_places_simple.geojson',bytes:4932147,sha256:'fd3fa867a320cbd5c5b6bb5bc550afeec2939fb2cef688e508007282a55ac42f'},
 {name:'zone1970.tab',revision:'IANA tzdb 2026f',url:'https://data.iana.org/time-zones/tzdb-2026f/zone1970.tab',bytes:17592,sha256:'5f23781702bf51408ff1581daa109ab3b9257fb433b1554e579d92172892c0cf'},
 {name:'LICENSE',revision:'IANA tzdb 2026f',url:'https://data.iana.org/time-zones/tzdb-2026f/LICENSE',bytes:252,sha256:'0613408568889f5739e5ae252b722a2659c02002839ad970a63dc5e9174b27cf'},
 {name:'version',revision:'IANA tzdb 2026f',url:'https://data.iana.org/time-zones/tzdb-2026f/version',bytes:6,sha256:'9f9a9e6bfd18cd6a0a4d65764931072577edcbb731981a068ef52bba6615b1de'}
].map(Object.freeze));

function zoneCountries(text){
 if(typeof text!=='string'||Buffer.byteLength(text)>128*1024)throw Error('Timezone input budget exceeded');
 const zones=new Map();
 for(const line of text.split(/\r?\n/)){
  if(!line.trim()||line.startsWith('#'))continue;
  const [countries,coordinates,zone]=line.split('\t');
  if(!/^[A-Z]{2}(?:,[A-Z]{2})*$/.test(countries||'')||!/^[+-]\d{4}(?:\d{2})?[+-]\d{5}(?:\d{2})?$/.test(coordinates||'')||!/^[-A-Za-z_]+(?:\/[-A-Za-z0-9_+]+){1,3}$/.test(zone||''))throw Error('Invalid timezone row');
  if(zones.has(zone))throw Error('Duplicate timezone row');
  zones.set(zone,new Set(countries.split(',')));
 }
 return zones;
}
const label=value=>{
 if(typeof value!=='string'||!value.trim()||value.length>160||/[\u0000-\u001f\u007f]/.test(value))throw Error('Invalid city name');
 return value.normalize('NFC').trim();
};

export function curatePlaces(geojson,zoneTable,selection){
 if(geojson?.type!=='FeatureCollection'||!Array.isArray(geojson.features)||!geojson.features.length||geojson.features.length>10000)throw Error('Natural Earth feature budget exceeded');
 if(!Array.isArray(selection)||!selection.length||selection.length>64)throw Error('Invalid place selection budget');
 const zones=zoneCountries(zoneTable),features=new Map(),seen=new Set();
 for(const feature of geojson.features){
  const id=feature?.properties?.ne_id;
  if(!Number.isSafeInteger(id)||id<1)throw Error('Invalid Natural Earth source ID');
  if(features.has(id))throw Error('Duplicate Natural Earth source ID');features.set(id,feature);
 }
 return selection.map(choice=>{
  const id=choice?.naturalEarthId;if(!Number.isSafeInteger(id)||id<1)throw Error('Invalid selected source ID');
  if(seen.has(id))throw Error('Duplicate selected source ID');seen.add(id);
  const feature=features.get(id);if(!feature)throw Error('Selected Natural Earth ID not found');
  const properties=feature.properties,name=label(properties.name),countrycode=properties.iso_a2;
  if(!/^[A-Z]{2}$/.test(countrycode||'')||['ZZ','XX','EU','UN'].includes(countrycode))throw Error('Invalid city country');
  const coordinates=feature.geometry?.coordinates;
  if(feature.geometry?.type!=='Point'||!Array.isArray(coordinates)||coordinates.length!==2||!coordinates.every(Number.isFinite)||Math.abs(coordinates[0])>180||Math.abs(coordinates[1])>90)throw Error('Invalid city point geometry');
  const timeZone=choice.timeZone;
  if(typeof timeZone!=='string'||!zones.get(timeZone)?.has(countrycode))throw Error('Selected timezone does not match city country');
  try{new Intl.DateTimeFormat('en',{timeZone}).format(0);}catch{throw Error('Selected IANA timezone is unsupported');}
  const aliases=[...new Set([name,...(properties.nameascii?[label(properties.nameascii)]:[])])].sort(compare);
  return{id:`ne-${id}`,naturalEarthId:id,name,countrycode,point:[coordinates[1],coordinates[0]],timeZone,aliases};
 });
}

export function renderPlaceModule(cities){
 const text='// Natural Earth v5.1.2 and IANA tzdb 2026f. Public-domain data.\n// Generated by scripts/build-place-data.mjs; do not edit derived values.\n'+
  `const data = ${JSON.stringify(cities,null,2)};\n`+
  'export const CURATED_PLACES = Object.freeze(data.map(city=>Object.freeze({...city,point:Object.freeze(city.point),aliases:Object.freeze(city.aliases)})));\n';
 if(Buffer.byteLength(text)>12*1024)throw Error('Curated place module exceeds 12 KiB budget');return text;
}

// Fixed local paths stay inside the checkout and never follow a directory/file
// symlink. Downloads write only these public cache files after all hashes pass.
async function ownedFile(relative,{createParents=false}={}){
 const canonical=await realpath(root),parts=relative.split('/');let parent=root;
 if(parts.some(part=>!part||part==='.'||part==='..'))throw Error('Invalid output path');
 for(const part of parts.slice(0,-1)){
  parent=path.join(parent,part);let entry;
  try{entry=await lstat(parent);}catch(error){if(error.code!=='ENOENT'||!createParents)throw error;await mkdir(parent);entry=await lstat(parent);}
  if(!entry.isDirectory()||entry.isSymbolicLink())throw Error('Place data directory must be an owned regular directory');
  const resolved=await realpath(parent),inside=path.relative(canonical,resolved);if(path.isAbsolute(inside)||inside==='..'||inside.startsWith('..'+path.sep))throw Error('Place data path escapes checkout');
 }
 const file=path.join(root,...parts);
 try{const entry=await lstat(file);if(!entry.isFile()||entry.isSymbolicLink())throw Error('Place data target must be a regular file');}catch(error){if(error.code!=='ENOENT')throw error;}
 return file;
}
async function downloadInput(input){
 const response=await fetch(input.url,{credentials:'omit',redirect:'error',signal:AbortSignal.timeout(90000)});
 if(response.status!==200)throw Error(`Place source unavailable: ${input.name}`);
 const reader=response.body?.getReader();if(!reader)throw Error('Missing source body');
 const chunks=[];let size=0;
 try{while(true){const next=await reader.read();if(next.done)break;size+=next.value.byteLength;if(size>input.bytes)throw Error(`Source byte budget exceeded: ${input.name}`);chunks.push(next.value);}}
 finally{await reader.cancel();reader.releaseLock();}
 const bytes=Buffer.concat(chunks);if(bytes.length!==input.bytes||digest(bytes)!==input.sha256)throw Error(`Place source integrity failed: ${input.name}`);return bytes;
}

export async function buildPlaceData({download=false,check=false}={}){
 if(download&&check)throw Error('--download and --check are separate operations');
 const source=new Map();
 for(const input of PLACE_INPUTS){
  let file;try{file=await ownedFile('.build/place-input/'+input.name,{createParents:download});}catch(error){if(error.code==='ENOENT')throw Error('Pinned local place inputs missing; use explicit --download',{cause:error});throw error;}
  let bytes;if(download)bytes=await downloadInput(input);else try{bytes=await readFile(file);}catch(error){if(error.code==='ENOENT')throw Error('Pinned local place inputs missing; use explicit --download',{cause:error});throw error;}
  if(bytes.length!==input.bytes||digest(bytes)!==input.sha256)throw Error(`Place source integrity failed: ${input.name}`);
  source.set(input.name,{file,bytes});
 }
 const selectedBytes=await readFile(path.join(root,'docs/provenance/place-selection.json'));
 if(selectedBytes.length>16*1024)throw Error('Place selection byte budget exceeded');
 const selection=JSON.parse(selectedBytes);if(selection.schemaVersion!==1)throw Error('Unsupported place selection schema');
 const cities=curatePlaces(JSON.parse(source.get(PLACE_INPUTS[0].name).bytes),new TextDecoder('utf-8',{fatal:true}).decode(source.get('zone1970.tab').bytes),selection.places);
 const text=renderPlaceModule(cities),provenance={schemaVersion:1,license:'Public domain',terms:['https://www.naturalearthdata.com/about/terms-of-use/','https://data.iana.org/time-zones/tzdb-2026f/LICENSE'],sources:PLACE_INPUTS,selection:{path:'docs/provenance/place-selection.json',bytes:selectedBytes.length,sha256:digest(selectedBytes)},output:{path:'site/assets/curated-places.js',bytes:Buffer.byteLength(text),sha256:digest(text),records:cities.length}};
 const outputs=[['site/assets/curated-places.js',text],['docs/provenance/place-data.json',JSON.stringify(provenance,null,2)+'\n']];
 if(check){for(const [relative,value]of outputs)if(await readFile(await ownedFile(relative),'utf8')!==value)throw Error('Place data output is stale: '+relative);}
 else{
  for(const [relative]of outputs)await ownedFile(relative,{createParents:true});
  if(download)for(const {file,bytes}of source.values())await writeFile(file,bytes);
  for(const [relative,value]of outputs)await writeFile(await ownedFile(relative),value);
 }
 return{check,download,records:cities.length,output:provenance.output};
}

if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url)){
 try{const args=process.argv.slice(2);if(args.length>1||args.some(value=>!['--download','--check'].includes(value)))throw Error('Usage: build-place-data.mjs [--download | --check]');process.stdout.write(JSON.stringify(await buildPlaceData({download:args.includes('--download'),check:args.includes('--check')}))+'\n');}
 catch(error){process.stderr.write(error.message+'\n');process.exitCode=1;}
}
