// Reproduce a small country-code sidecar without rewriting cached map assets.
// Reads only the pinned public-domain inputs; no network request or geocoder.
import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { curateGeometry } from './build-map-data.mjs';

const root = path.resolve(import.meta.dirname, '..');
const digest = value => createHash('sha256').update(value).digest('hex');
const alpha2 = value => typeof value === 'string' && /^[A-Z]{2}$/.test(value);
const hasPoint = coordinates => typeof coordinates[0] === 'number' || coordinates.some(hasPoint);
export function identifyMapCountries(rawFeatures, curatedFeatures, tolerance) {
  const source = rawFeatures.filter(row => row.geometry && Array.isArray(row.geometry.coordinates) && hasPoint(row.geometry.coordinates));
  assert.equal(source.length, curatedFeatures.length, 'Country feature count changed');
  return source.map((row, index) => {
    // Compare the published JSON representation: JSON serializes -0 as 0.
    // Report only the two hashes on a mismatch, never a multi-MiB geometry dump.
    assert.equal(digest(JSON.stringify(curateGeometry(row.geometry, tolerance))),
      digest(JSON.stringify(curatedFeatures[index].geometry)), `Country geometry differs at ${index}`);
    // ISO_A2_EH covers source records such as France/XK whose ISO_A2 is -99.
    // Postal abbreviations are not country identifiers (Somaliland's SL would
    // otherwise color Sierra Leone). Unidentified polygons stay unidentified.
    return [row.properties?.ISO_A2_EH, row.properties?.ISO_A2].find(alpha2) || '';
  });
}
export async function buildMapCountryIdentifiers({ sourceDirectory = path.join(root, '.build/map-source'), write = true } = {}) {
  const provenance = JSON.parse(await readFile(path.join(root, 'docs/provenance/map-data.json'), 'utf8'));
  const identifiers = {}, assets = {}, sources = [];
  for (const [kind, name, tolerance] of [['world', 'ne_50m_admin_0_countries', 0.01], ['detail', 'ne_10m_admin_0_countries', 0.0015]]) {
    const input = provenance.sources.find(row => row.name === name);
    assert.ok(input, 'Missing pinned source');
    const source = await readFile(path.join(sourceDirectory, name + '.geojson'));
    assert.equal(source.length, input.bytes, name); assert.equal(digest(source), input.sha256, name);
    const output = provenance.outputs.find(row => new RegExp(`/map-${kind}-[a-f0-9]{8}\\.js$`).test(row.path));
    assert.ok(output, 'Missing pinned map output');
    const bytes = await readFile(path.join(root, output.path));
    assert.equal(bytes.length, output.bytes, output.path); assert.equal(digest(bytes), output.sha256, output.path);
    const text = bytes.toString('utf8'), prefix = `export const MAP_${kind.toUpperCase()} = `;
    assert.equal(text.split(prefix).length, 2, 'Map asset is not a data-only module');
    const curated = JSON.parse(text.slice(text.indexOf(prefix) + prefix.length).trim().replace(/;$/, ''));
    const codes = identifyMapCountries(JSON.parse(source).features, curated.countries.features, tolerance);
    identifiers[kind] = { asset: path.basename(output.path), codes };
    assets[kind] = { asset: path.basename(output.path), sha256: output.sha256, features: codes.length,
      codesSha256: digest(JSON.stringify(codes)), geometrySha256: digest(JSON.stringify(curated.countries.features.map(row => row.geometry))) };
    sources.push({ name: input.name, bytes: input.bytes, sha256: input.sha256 });
  }
  const module = '// Natural Earth v5.1.2. Public domain. Generated by scripts/build-map-country-identifiers.mjs.\n'
    + '// Each ordinal is verified against the exact existing curated polygon geometry.\n'
    + `export const MAP_COUNTRY_IDENTIFIERS = ${JSON.stringify(identifiers)};\n`;
  const metadata = { schemaVersion: 1, sourceRevision: provenance.sourceRevision, license: provenance.license,
    method: 'Exact serialized curateGeometry correspondence (JSON normalizes negative zero); ISO_A2_EH then ISO_A2; unidentified polygons remain blank.',
    sources, assets, output: { path: 'site/assets/map-country-identifiers.js', bytes: Buffer.byteLength(module), sha256: digest(module) } };
  if (write) {
    await writeFile(path.join(root, metadata.output.path), module);
    await writeFile(path.join(root, 'docs/provenance/map-country-identifiers.json'), JSON.stringify(metadata, null, 2) + '\n');
  }
  return { module, metadata };
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const supplied = process.argv.find(value => value.startsWith('--source-dir='));
  const result = await buildMapCountryIdentifiers({ ...(supplied ? { sourceDirectory: path.resolve(supplied.slice(13)) } : {}) });
  console.log(JSON.stringify({ output: result.metadata.output, assets: result.metadata.assets }));
}
